/**
 * Portuguese for Portuguese speakers, Spanish for Spanish speakers, English for everyone
 * else — a German player is better served by English than by either. No signal at all still
 * means Portuguese: that is the case during static web rendering, and the site is pt-first.
 */
export function resolveLanguage(languageCode: string | null | undefined): SupportedLanguage {
  if (!languageCode) return 'pt-PT';
  const code = languageCode.toLowerCase();
  if (code.startsWith('pt')) return 'pt-PT';
  return code.startsWith('es') ? 'es' : 'en';
}

export function translate(language: SupportedLanguage, key: string, variables: Variables = {}): string {
  const template = messages[language][key] ?? messages['pt-PT'][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(variables[name] ?? `{${name}}`));
}

export type Translate = (key: string, variables?: Variables) => string;

/** The keys of the message catalogue, for tests that check both languages agree. */
export function messageKeys(language: SupportedLanguage): string[] {
  return Object.keys(messages[language]);
}

